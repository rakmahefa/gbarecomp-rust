//! AOT Rust source emitter for the currently supported IR subset.
//!
//! The emitter refuses reports containing any unresolved or unsupported path.
//! It never produces runtime decoding, interpretation, or JIT code.

use std::fmt::Write as _;

use super::RecompileError;
use super::ir::{
    AnalysisReport, BasicBlock, BlockTerminator, DataProcessingOpcode, IrInstruction, IrOperation,
};

/// Emit a standalone Rust module containing statically specialized block functions.
///
/// The generated module has no dependency on this crate. A downstream build can
/// compile it with rustc/Cargo and wire its `RecompiledState` to a hardware
/// runtime. This first slice models registers and CPSR only; no GBA MMIO/device
/// semantics are implied by this API.
pub fn emit_rust_source(report: &AnalysisReport) -> Result<String, RecompileError> {
    if let Some(error) = report.first_error() {
        return Err(error);
    }
    if report.blocks.is_empty() {
        return Err(RecompileError::UnresolvedStaticTarget {
            instruction_address: 0x0800_0000,
            target_address: 0x0800_0000,
        });
    }

    for block in &report.blocks {
        if matches!(block.terminator, BlockTerminator::Indirect) {
            return Err(RecompileError::UnresolvedIndirectControlFlow {
                instruction_address: block.start,
            });
        }
        if matches!(block.terminator, BlockTerminator::Unsupported) {
            let last = block.instructions.last();
            return Err(RecompileError::UnsupportedInstruction {
                address: last.map_or(block.start, |instruction| instruction.address),
                opcode: last.map_or(0, |instruction| instruction.raw),
                instruction_set: block.instruction_set,
            });
        }
    }

    let mut output = String::from(
        r#"// Generated by gbarecomp-rust. Do not edit by hand.
#![allow(dead_code)]

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecompiledState {
    pub regs: [u32; 16],
    pub cpsr: u32,
}

impl Default for RecompiledState {
    fn default() -> Self {
        Self { regs: [0; 16], cpsr: 0x1F }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Flow {
    Next { target: u32, thumb: bool },
    Branch { target: u32, thumb: bool },
    Call { target: u32, return_address: u32, thumb: bool },
    Exit,
}

const N: u32 = 1 << 31;
const Z: u32 = 1 << 30;
const T: u32 = 1 << 5;
const C: u32 = 1 << 29;
const V: u32 = 1 << 28;

fn set_thumb(state: &mut RecompiledState, thumb: bool) {
    state.cpsr = (state.cpsr & !T) | if thumb { T } else { 0 };
}

fn condition_passed(cpsr: u32, condition: u8) -> bool {
    let n = cpsr & N != 0;
    let z = cpsr & Z != 0;
    let c = cpsr & C != 0;
    let v = cpsr & V != 0;
    match condition & 0x0F {
        0x0 => z,
        0x1 => !z,
        0x2 => c,
        0x3 => !c,
        0x4 => n,
        0x5 => !n,
        0x6 => v,
        0x7 => !v,
        0x8 => c && !z,
        0x9 => !c || z,
        0xA => n == v,
        0xB => n != v,
        0xC => !z && n == v,
        0xD => z || n != v,
        0xE => true,
        _ => false,
    }
}

fn update_nz(state: &mut RecompiledState, result: u32) {
    state.cpsr &= !(N | Z);
    if result & 0x8000_0000 != 0 { state.cpsr |= N; }
    if result == 0 { state.cpsr |= Z; }
}

fn update_logic_flags(state: &mut RecompiledState, result: u32, shifter_carry: Option<bool>) {
    update_nz(state, result);
    if let Some(carry) = shifter_carry {
        state.cpsr = (state.cpsr & !C) | if carry { C } else { 0 };
    }
}

fn update_add_flags(state: &mut RecompiledState, lhs: u32, rhs: u32, result: u32) {
    let wide = u64::from(lhs) + u64::from(rhs);
    let carry = wide > u64::from(u32::MAX);
    let overflow = (!(lhs ^ rhs) & (lhs ^ result) & 0x8000_0000) != 0;
    state.cpsr &= !(N | Z | C | V);
    if result & 0x8000_0000 != 0 { state.cpsr |= N; }
    if result == 0 { state.cpsr |= Z; }
    if carry { state.cpsr |= C; }
    if overflow { state.cpsr |= V; }
}

fn update_sub_flags(state: &mut RecompiledState, lhs: u32, rhs: u32, result: u32) {
    let carry = lhs >= rhs;
    let overflow = ((lhs ^ rhs) & (lhs ^ result) & 0x8000_0000) != 0;
    state.cpsr &= !(N | Z | C | V);
    if result & 0x8000_0000 != 0 { state.cpsr |= N; }
    if result == 0 { state.cpsr |= Z; }
    if carry { state.cpsr |= C; }
    if overflow { state.cpsr |= V; }
}

"#,
    );

    for block in &report.blocks {
        emit_block(&mut output, block)?;
    }

    output.push_str(
        "\npub fn execute_block(address: u32, thumb: bool, state: &mut RecompiledState) -> Result<Flow, &'static str> {\n    match (address, thumb) {\n",
    );
    for block in &report.blocks {
        let _ = writeln!(
            output,
            "        (0x{:08X}, {}) => block_{:08X}_{}(state),",
            block.start,
            block.instruction_set == super::InstructionSet::Thumb,
            block.start,
            state_suffix(block.instruction_set)
        );
    }
    output.push_str(
        "        _ => Err(\"no statically generated block for guest PC/state\"),\n    }\n}\n",
    );
    Ok(output)
}

fn emit_block(output: &mut String, block: &BasicBlock) -> Result<(), RecompileError> {
    let suffix = state_suffix(block.instruction_set);
    let _ = writeln!(
        output,
        "\nfn block_{:08X}_{}(state: &mut RecompiledState) -> Result<Flow, &'static str> {{",
        block.start, suffix
    );
    let thumb = block.instruction_set == super::InstructionSet::Thumb;
    let _ = writeln!(output, "    set_thumb(state, {thumb});");

    for instruction in &block.instructions {
        emit_instruction(output, instruction)?;
    }

    emit_terminator(output, block)?;
    output.push_str("}\n");
    Ok(())
}

fn emit_instruction(
    output: &mut String,
    instruction: &IrInstruction,
) -> Result<(), RecompileError> {
    match &instruction.operation {
        IrOperation::Nop => {
            let _ = writeln!(output, "    // NOP at 0x{:08X}", instruction.address);
        }
        IrOperation::ThumbMoveImmediate { rd, immediate } => {
            let _ = writeln!(
                output,
                "    state.regs[{rd}] = {immediate};\n    update_nz(state, state.regs[{rd}]);"
            );
        }
        IrOperation::ArmDataProcessingImmediate {
            condition,
            opcode,
            set_flags,
            rn,
            rd,
            value,
            shifter_carry,
        } => {
            let _ = writeln!(
                output,
                "    if condition_passed(state.cpsr, {condition}) {{"
            );
            if *rn == 15 {
                let visible_pc = instruction.address.wrapping_add(8);
                let _ = writeln!(output, "        let lhs = 0x{visible_pc:08X}_u32;");
            } else {
                let _ = writeln!(output, "        let lhs = state.regs[{rn}];");
            }
            let _ = writeln!(output, "        let rhs = 0x{value:08X}_u32;");
            let expression = match opcode {
                DataProcessingOpcode::And | DataProcessingOpcode::Test => "lhs & rhs",
                DataProcessingOpcode::ExclusiveOr | DataProcessingOpcode::TestExclusiveOr => {
                    "lhs ^ rhs"
                }
                DataProcessingOpcode::Subtract | DataProcessingOpcode::Compare => {
                    "lhs.wrapping_sub(rhs)"
                }
                DataProcessingOpcode::Add => "lhs.wrapping_add(rhs)",
                DataProcessingOpcode::Or => "lhs | rhs",
                DataProcessingOpcode::Move => "rhs",
                DataProcessingOpcode::BitClear => "lhs & !rhs",
                DataProcessingOpcode::MoveNot => "!rhs",
            };
            let _ = writeln!(output, "        let result = {expression};");

            if opcode.writes_destination() {
                let _ = writeln!(output, "        state.regs[{rd}] = result;");
            }

            if *set_flags || opcode.updates_flags_by_definition() {
                match opcode {
                    DataProcessingOpcode::Add => {
                        let _ =
                            writeln!(output, "        update_add_flags(state, lhs, rhs, result);");
                    }
                    DataProcessingOpcode::Subtract | DataProcessingOpcode::Compare => {
                        let _ =
                            writeln!(output, "        update_sub_flags(state, lhs, rhs, result);");
                    }
                    _ => {
                        let carry = match shifter_carry {
                            Some(true) => "Some(true)",
                            Some(false) => "Some(false)",
                            None => "None",
                        };
                        let _ = writeln!(
                            output,
                            "        update_logic_flags(state, result, {carry});"
                        );
                    }
                }
            }
            output.push_str("    }\n");
        }
    }
    Ok(())
}

fn emit_terminator(output: &mut String, block: &BasicBlock) -> Result<(), RecompileError> {
    match block.terminator {
        BlockTerminator::Fallthrough {
            target,
            instruction_set,
        } => {
            let thumb = instruction_set == super::InstructionSet::Thumb;
            let _ = writeln!(output, "    state.regs[15] = 0x{target:08X};");
            let _ = writeln!(
                output,
                "    Ok(Flow::Next {{ target: 0x{target:08X}, thumb: {thumb} }})"
            );
        }
        BlockTerminator::Branch {
            condition,
            target,
            instruction_set,
            link,
            return_address,
            fallthrough,
        } => {
            let thumb = instruction_set == super::InstructionSet::Thumb;
            let _ = writeln!(output, "    if condition_passed(state.cpsr, {condition}) {{");
            if link {
                let _ = writeln!(output, "        state.regs[14] = 0x{return_address:08X};");
            }
            let _ = writeln!(output, "        state.regs[15] = 0x{target:08X};");
            if link {
                let _ = writeln!(
                    output,
                    "        Ok(Flow::Call {{ target: 0x{target:08X}, return_address: 0x{return_address:08X}, thumb: {thumb} }})"
                );
            } else {
                let _ = writeln!(
                    output,
                    "        Ok(Flow::Branch {{ target: 0x{target:08X}, thumb: {thumb} }})"
                );
            }
            output.push_str("    } else {\n");
            if let Some(fallthrough) = fallthrough {
                let _ = writeln!(output, "        state.regs[15] = 0x{fallthrough:08X};");
                let _ = writeln!(
                    output,
                    "        Ok(Flow::Next {{ target: 0x{fallthrough:08X}, thumb: {thumb} }})"
                );
            } else {
                output.push_str(
                    "        Err(\"unconditional branch condition unexpectedly failed\")\n",
                );
            }
            output.push_str("    }\n");
        }
        BlockTerminator::ConditionalBranch {
            condition,
            target,
            fallthrough,
            instruction_set,
        } => {
            let thumb = instruction_set == super::InstructionSet::Thumb;
            let _ = writeln!(output, "    if condition_passed(state.cpsr, {condition}) {{");
            let _ = writeln!(output, "        state.regs[15] = 0x{target:08X};");
            let _ = writeln!(
                output,
                "        Ok(Flow::Branch {{ target: 0x{target:08X}, thumb: {thumb} }})"
            );
            output.push_str("    } else {\n");
            let _ = writeln!(output, "        state.regs[15] = 0x{fallthrough:08X};");
            let _ = writeln!(
                output,
                "        Ok(Flow::Next {{ target: 0x{fallthrough:08X}, thumb: {thumb} }})"
            );
            output.push_str("    }\n");
        }
        BlockTerminator::Exit => output.push_str("    Ok(Flow::Exit)\n"),
        BlockTerminator::Unsupported => {
            return Err(RecompileError::UnsupportedInstruction {
                address: block.start,
                opcode: block
                    .instructions
                    .last()
                    .map_or(0, |instruction| instruction.raw),
                instruction_set: block.instruction_set,
            });
        }
        BlockTerminator::Indirect => {
            return Err(RecompileError::UnresolvedIndirectControlFlow {
                instruction_address: block.start,
            });
        }
    }
    Ok(())
}

const fn state_suffix(state: super::InstructionSet) -> &'static str {
    match state {
        super::InstructionSet::Arm => "arm",
        super::InstructionSet::Thumb => "thumb",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::recompiler::InstructionSet;
    use crate::recompiler::ir::{
        AnalysisReport, BasicBlock, BlockTerminator, IrInstruction, IrOperation,
    };
    use std::process::Command;

    #[test]
    fn refuses_codegen_if_analysis_has_any_unresolved_diagnostic() {
        let report = AnalysisReport {
            blocks: vec![],
            diagnostics: vec![RecompileError::UnresolvedIndirectControlFlow {
                instruction_address: 0x0800_0000,
            }],
            instruction_count: 0,
            instruction_limit: 100,
            reached_instruction_limit: false,
        };
        assert!(matches!(
            emit_rust_source(&report),
            Err(RecompileError::UnresolvedIndirectControlFlow { .. })
        ));
    }

    #[test]
    fn emitted_source_compiles_with_rustc() {
        let report = AnalysisReport {
            blocks: vec![
                BasicBlock {
                    start: 0x0800_0000,
                    instruction_set: InstructionSet::Arm,
                    instructions: vec![IrInstruction {
                        address: 0x0800_0000,
                        raw: 0xE3A0_0001,
                        instruction_set: InstructionSet::Arm,
                        operation: IrOperation::ArmDataProcessingImmediate {
                            condition: 0xE,
                            opcode: DataProcessingOpcode::Move,
                            set_flags: false,
                            rn: 0,
                            rd: 0,
                            value: 1,
                            shifter_carry: None,
                        },
                    }],
                    terminator: BlockTerminator::Branch {
                        condition: 0xE,
                        target: 0x0800_0008,
                        instruction_set: InstructionSet::Arm,
                        link: false,
                        return_address: 0x0800_0004,
                        fallthrough: None,
                    },
                },
                BasicBlock {
                    start: 0x0800_0008,
                    instruction_set: InstructionSet::Arm,
                    instructions: vec![IrInstruction {
                        address: 0x0800_0008,
                        raw: 0xE1A0_0000,
                        instruction_set: InstructionSet::Arm,
                        operation: IrOperation::Nop,
                    }],
                    terminator: BlockTerminator::Exit,
                },
                BasicBlock {
                    start: 0x0800_0010,
                    instruction_set: InstructionSet::Arm,
                    instructions: vec![IrInstruction {
                        address: 0x0800_0010,
                        raw: 0xE24F_0008,
                        instruction_set: InstructionSet::Arm,
                        operation: IrOperation::ArmDataProcessingImmediate {
                            condition: 0xE,
                            opcode: DataProcessingOpcode::Subtract,
                            set_flags: false,
                            rn: 15,
                            rd: 0,
                            value: 8,
                            shifter_carry: None,
                        },
                    }],
                    terminator: BlockTerminator::Exit,
                },
            ],
            diagnostics: vec![],
            instruction_count: 4,
            instruction_limit: 100,
            reached_instruction_limit: false,
        };
        let mut source = emit_rust_source(&report).expect("valid IR should emit Rust");
        source.push_str(
            r#"
#[test]
fn generated_mov_branch_and_pc_operand_execute_natively() {
    let mut state = RecompiledState::default();
    assert_eq!(
        execute_block(0x0800_0000, false, &mut state),
        Ok(Flow::Branch { target: 0x0800_0008, thumb: false })
    );
    assert_eq!(state.regs[0], 1);
    assert_eq!(state.regs[15], 0x0800_0008);
    assert_eq!(state.cpsr & T, 0);
    assert_eq!(
        execute_block(0x0800_0008, false, &mut state),
        Ok(Flow::Exit)
    );

    let mut pc_state = RecompiledState::default();
    assert_eq!(
        execute_block(0x0800_0010, false, &mut pc_state),
        Ok(Flow::Exit)
    );
    // SUB r0, pc, #8 reads PC as instruction address + 8 on ARM.
    assert_eq!(pc_state.regs[0], 0x0800_0010);
}
"#,
        );

        let temp = std::env::temp_dir();
        let stem = format!("gbarecomp-generated-smoke-{}", std::process::id());
        let source_path = temp.join(format!("{stem}.rs"));
        let binary_path = temp.join(stem);
        std::fs::write(&source_path, source).expect("write generated source");
        let compile = Command::new("rustc")
            .arg("--edition=2024")
            .arg("--test")
            .arg(&source_path)
            .arg("-o")
            .arg(&binary_path)
            .output()
            .expect("rustc must be installed in the Cargo test environment");
        assert!(
            compile.status.success(),
            "generated Rust failed to compile:\n{}",
            String::from_utf8_lossy(&compile.stderr)
        );
        let execute = Command::new(&binary_path)
            .output()
            .expect("execute generated native test binary");
        let _ = std::fs::remove_file(&source_path);
        let _ = std::fs::remove_file(&binary_path);
        assert!(
            execute.status.success(),
            "generated Rust semantics failed:\n{}",
            String::from_utf8_lossy(&execute.stdout)
        );
    }
}
